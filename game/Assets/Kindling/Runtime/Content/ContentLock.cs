using System.Collections.Generic;
using System.Linq;
using Kindling.Core.Json;

namespace Kindling.Content
{
    /// <summary>
    /// content.lock.json: the permanent key → network id table. Ids are assigned once and never reused,
    /// even after a definition is removed (it moves to "retired"), so saves and the network stay valid.
    /// </summary>
    public sealed class ContentLock
    {
        public const int Version = 1;

        readonly Dictionary<string, ushort> m_Ids = new Dictionary<string, ushort>();
        readonly Dictionary<string, ushort> m_Retired = new Dictionary<string, ushort>();

        public IReadOnlyDictionary<string, ushort> Ids => m_Ids;

        public IReadOnlyDictionary<string, ushort> Retired => m_Retired;

        public bool TryGet(string key, out ushort id) => m_Ids.TryGetValue(key, out id);

        public static ContentLock Parse(string json)
        {
            var result = new ContentLock();
            JsonValue root = JsonReader.Parse(json);
            foreach (var pair in root.Required("ids").Members)
            {
                result.m_Ids[pair.Key] = checked((ushort)pair.Value.AsInt());
            }

            JsonValue retired = root.Get("retired");
            if (retired != null)
            {
                foreach (var pair in retired.Members)
                {
                    result.m_Retired[pair.Key] = checked((ushort)pair.Value.AsInt());
                }
            }

            return result;
        }

        public ushort NextId
        {
            get
            {
                int max = 0;
                foreach (ushort id in m_Ids.Values.Concat(m_Retired.Values))
                {
                    max = System.Math.Max(max, id);
                }

                return checked((ushort)(max + 1));
            }
        }

        /// <summary>Adds ids for new keys and retires keys no longer defined. Returns true if anything changed.</summary>
        public bool Update(IEnumerable<string> definedKeys)
        {
            bool changed = false;
            var defined = new HashSet<string>(definedKeys);
            foreach (string key in m_Ids.Keys.Where(k => !defined.Contains(k)).ToList())
            {
                m_Retired[key] = m_Ids[key];
                m_Ids.Remove(key);
                changed = true;
            }

            foreach (string key in defined.OrderBy(k => k, System.StringComparer.Ordinal))
            {
                if (m_Ids.ContainsKey(key))
                {
                    continue;
                }

                if (m_Retired.TryGetValue(key, out ushort old))
                {
                    m_Ids[key] = old; // a re-added key gets its old id back
                    m_Retired.Remove(key);
                }
                else
                {
                    m_Ids[key] = NextId;
                }

                changed = true;
            }

            return changed;
        }

        public string ToJson()
        {
            JsonValue root = JsonValue.NewObject();
            root.Set("version", Version);
            root.Set("comment", "Generated by `dotnet run --project sim/Kindling.ContentTool -- update-lock`. Ids are permanent; never edit or reuse them.");
            JsonValue ids = JsonValue.NewObject();
            foreach (var pair in m_Ids.OrderBy(p => p.Value))
            {
                ids.Set(pair.Key, pair.Value);
            }

            root.Set("ids", ids);
            JsonValue retired = JsonValue.NewObject();
            foreach (var pair in m_Retired.OrderBy(p => p.Value))
            {
                retired.Set(pair.Key, pair.Value);
            }

            root.Set("retired", retired);
            return JsonWriter.Write(root);
        }
    }
}
