using System.Linq;
using Kindling.Core.Json;

namespace Kindling.Content
{
    /// <summary>Writes content-export.json: the content catalogue for the backend and web console.</summary>
    public static class ContentExporter
    {
        public static string Export(ContentDatabase db)
        {
            JsonValue root = JsonValue.NewObject();
            root.Set("version", 1);
            root.Set("comment", "Generated by `dotnet run --project sim/Kindling.ContentTool -- export`. Do not edit.");

            JsonValue items = JsonValue.NewArray();
            foreach (ItemDef i in db.Items.OrderBy(i => i.NetId))
            {
                JsonValue o = Common(i);
                o.Set("category", i.Category.ToString().ToLowerInvariant());
                o.Set("stack", i.StackSize);
                if (i.Slot != EquipSlot.None)
                {
                    o.Set("slot", i.Slot.ToString().ToLowerInvariant());
                }

                items.Add(o);
            }

            JsonValue recipes = JsonValue.NewArray();
            foreach (RecipeDef r in db.Recipes.OrderBy(r => r.NetId))
            {
                JsonValue o = Common(r);
                o.Set("output", r.Output.ItemKey.Value);
                o.Set("amount", r.Output.Amount);
                o.Set("station", r.Station.ToString());
                o.Set("seconds", r.Seconds);
                JsonValue inputs = JsonValue.NewObject();
                foreach (ItemAmount a in r.Inputs)
                {
                    inputs.Set(a.ItemKey.Value, a.Amount);
                }

                o.Set("inputs", inputs);
                recipes.Add(o);
            }

            JsonValue nodes = JsonValue.NewArray();
            foreach (NodeDef n in db.Nodes.OrderBy(n => n.NetId))
            {
                JsonValue o = Common(n);
                o.Set("kind", n.Kind.ToString().ToLowerInvariant());
                o.Set("primary", n.PrimaryKey.Value);
                nodes.Add(o);
            }

            JsonValue entities = JsonValue.NewArray();
            foreach (EntityDef e in db.Entities.OrderBy(e => e.NetId))
            {
                JsonValue o = Common(e);
                o.Set("kind", e.Kind.ToString());
                entities.Add(o);
            }

            JsonValue loot = JsonValue.NewArray();
            foreach (LootTableDef t in db.LootTables.OrderBy(t => t.NetId))
            {
                loot.Add(Common(t));
            }

            root.Set("items", items);
            root.Set("recipes", recipes);
            root.Set("nodes", nodes);
            root.Set("entities", entities);
            root.Set("lootTables", loot);
            return JsonWriter.Write(root);
        }

        static JsonValue Common(ContentDef d)
        {
            JsonValue o = JsonValue.NewObject();
            o.Set("key", d.Key.Value);
            o.Set("netId", d.NetId);
            o.Set("name", d.Name ?? string.Empty);
            return o;
        }
    }
}
